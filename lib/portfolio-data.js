const eventBySlug = new Map(eventPortfolio.map((event) => [event.slug, event]))

function eventHref(event) {
  if (event.link) return event.link
  if (EVENT_SUBPAGE_SLUGS.has(event.slug)) return `/event-it/${event.slug}`
  return '/event-it/portfolio'
}

const majorEventProjects = eventPortfolioSlugs
  .map((slug, index) => {
    const event = eventBySlug.get(slug)
    if (!event) return null
    return {
      name: event.name,
      slug: `event-${event.slug}`,
      type: 'Major Events',
      industry: event.category === 'Concerts' ? 'Live Entertainment' : event.category === 'National' ? 'Government & Community' : 'Sports & Venues',
      location: event.location,
      year: event.year,
      services: eventServiceMap[event.slug] || [service.eventIt, service.eventWifi],
      proofPoint: eventProof[event.slug] || event.tech,
      challenge: 'Live-event infrastructure with no room for avoidable downtime.',
      scope: event.tech,
      outcome: 'Delivered by IP Care Technologies',
      featured: featuredEventSlugs.includes(event.slug),
      priority: index + 1,
      image: event.img,
      imageAlt: `${event.name}, event IT infrastructure delivered by IP Care`,
      imageVerified: true,
      imageCaption: 'IP Care event delivery visual',
      relatedHref: eventHref(event),
    }
  })
  .filter(Boolean)

