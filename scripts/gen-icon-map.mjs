// Generates lib/icon-map.js: named imports of only the lucide-react icons the
// site refers to by *string* name (e.g. `icon: 'ShieldCheck'` in lib/*-data.js).
//
// Why: client components used to resolve those names with
// `import * as Icons from 'lucide-react'` + `Icons[name]`. A dynamic lookup
// can't be tree-shaken, so every page using it shipped all ~1,500 icons
// (~180 KB gzipped). ICONS[name] from lib/icon-map.js ships only these.
//
// Runs automatically in `prebuild`, so an icon name added to a data file is
// picked up on the next build. Over-inclusion is harmless (a few hundred bytes
// per icon); a name that isn't a lucide export is simply skipped.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const lucide = require('lucide-react')

const ROOTS = ['app', 'components', 'lib']
const OUT = 'lib/icon-map.js'
// Fallbacks used by the ICONS[name] || Icons.X call sites.
const ALWAYS = ['Award', 'Check', 'Code2', 'Package', 'Server', 'Shield', 'Wifi']

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name)
    if (entry.isDirectory()) yield* walk(p)
    else if (/\.(js|jsx|mjs)$/.test(entry.name) && p.replace(/\\/g, '/') !== OUT) yield p
  }
}

const names = new Set(ALWAYS)
for (const root of ROOTS) {
  for (const file of walk(root)) {
    const src = readFileSync(file, 'utf8')
    for (const [, name] of src.matchAll(/['"`]([A-Z][A-Za-z0-9]+)['"`]/g)) {
      if (!name.endsWith('Icon') && lucide[name] && typeof lucide[name] === 'object') names.add(name)
    }
  }
}

const sorted = [...names].sort()
const out = `// GENERATED by scripts/gen-icon-map.mjs (runs in prebuild) — do not edit.
// Only the lucide icons referenced by string name anywhere in app/, components/
// or lib/. Use ICONS[name] instead of \`import * as Icons\` + Icons[name], which
// pulls the entire icon library into the client bundle.
import {
${sorted.map((n) => `  ${n},`).join('\n')}
} from 'lucide-react'

export const ICONS = {
${sorted.map((n) => `  ${n},`).join('\n')}
}
`
writeFileSync(OUT, out)
console.log(`${OUT}: ${sorted.length} icons`)
